package string;

public class startswith_contains {
    public static void main(String[] args) {
        String str = "hello everyone my name is dipanshu";

        System.out.println(str.contains("one"));
        System.out.println(str.contains("ashu"));
        System.out.println(str.contains("he"));
        System.out.println(str.startsWith("every"));
        System.out.println(str.startsWith("he"));
        System.out.println(str.startsWith("hello e"));
    }
}
